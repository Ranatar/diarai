names = "Адам Сиф Енос Каинан Малелеил Иаред Енох Мафусал Ламех Ной Сим Арфаксад Сала Евер Фалек Рагав Серух Нахор Фарра Авраам Исаак Иаков".split()
age = [0, 130, 105, 90, 70, 65, 162, 65, 187, 182, 502, 100, 35, 30, 34, 30, 32, 30, 29, 70, 100, 60]
life = [930, 912, 905, 910, 895, 962, 365, 969, 777, 950, 600, 438, 433, 464, 239, 239, 230, 148, 205, 175, 180, 147]
b = 0
P = {}
for n, a, l in zip(names, age, life):
    b += a
    P[n] = (b, b + l)
    print(n, b, b + l)
flood = P["Ной"][0] + 600
print("потоп", flood)
print("умерли в год потопа", [n for n in names if P[n][1] == flood])
print("Ламех и Адам", P["Адам"][1] - P["Ламех"][0])
print("Ной умер, Аврааму", P["Ной"][1] - P["Авраам"][0])
print("Сим после Авраама", P["Сим"][1] - P["Авраам"][1], "Сим и Иаков", P["Сим"][1] - P["Иаков"][0])
print("Евер после рожд. Иакова", P["Евер"][1] - P["Иаков"][0])
print("пережили Авраама", [n for n in names[:19] if P[n][1] > P["Авраам"][1]])
print("живы в 1948", [n for n in names if P[n][0] <= 1948 <= P[n][1]])
def ov(x, y):
    return max(0, min(P[x][1], P[y][1]) - max(P[x][0], P[y][0]))
print("Адам-Мафусал", ov("Адам", "Мафусал"), "Мафусал-Сим", ov("Мафусал", "Сим"), "Сим-Авраам", ov("Сим", "Авраам"))
