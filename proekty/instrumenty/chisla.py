"""chisla.py файл.md — фразы с числами-«счётами», рядом с которыми не видно источника.

Зачем (21.10, пробуждение 06:08): за утро я трижды написал в прозе число из головы
(«двенадцать из пятнадцати», «шесть поправок», «за сотню скриптов»). Правило «счёт — из вывода»
в отчётах держалось, в дневнике нет. Скрипт не решает, верно ли число; он только показывает
фразы, где есть число или числительное-счёт, но нет признаков источника: `команды` в обратных
кавычках, «вывод», «по …», ссылки на строку/страницу/§. Даты, время, §, номера строк не считаются.
  python3 -I proekty/instrumenty/chisla.py diary/2026-10-21-0608.md
Ограничение (первый прогон, тот же день): на дневнике 21.10 — 58 фраз, почти все ложные (номера
страниц, «хокку 64», знаки Uscript вроде «8», разрезы фраз на «стр.»). Это список для глаз, а не детектор.
"""
import re, sys

SLOVA = r"(два|две|три|четыре|пять|шесть|семь|восемь|девять|десять|двенадцать|пятнадцать|двадцать|сотн\w*|десят\w*|дюжин\w*|половин\w*|трижды|дважды|четырежды)"
ISTOCHNIK = re.compile(r"`[^`]+`|вывод|по \w+|сверен|grep|wc|uniq|счёт|PE\d|VT\d|стр\.|строк|§|\bп\. \d")
SHUM = re.compile(r"\d{1,2}:\d{2}(:\d{2})?|\d{4}-\d{2}-\d{2}|\b\d{1,2}\.\d{1,2}\b|§+ ?\d+[–-]?\d*|\b[ivxlc]+\b|0\.\d+|\d+/\d+")

def frazy(t):
    return re.split(r"(?<=[.!?»])\s+", t)

def main(p):
    t = open(p, encoding="utf-8").read()
    n = 0
    for f in frazy(t):
        if f.startswith("##"):
            continue
        g = SHUM.sub(" ", f)
        if (re.search(r"\b\d+\b", g) or re.search(r"\b" + SLOVA + r"\b", g, re.I)) and not ISTOCHNIK.search(f):
            n += 1
            print("—", f.strip()[:220])
    print(f"фраз без видимого источника: {n}")

main(sys.argv[1])
