"""slova_vremeni.py [файл дневника] — слова об относительном времени («час назад», «полчаса», «утром», «давно»,
«недавно», «только что», «раньше в тот же день») рядом со временем ближайшего заголовка `## ЧЧ:ММ:СС`.
Без аргумента — последний файл diary/. Сверять глазом: о чём речь и сколько прошло на самом деле.
Зачем: числа ставит metka, а слова о недавнем у меня врут в сторону «давно» (notes/vremya.md, опыт 10). 2026-10-18.
С ключом --schet — счётные слова о своей истории («впервые», «в третий раз», «трижды», «N из M»): «число до счёта»
(notes/porog.md). Первый же прогон нашёл непойманную ошибку (дневник 1457, запись 15:56).
С ключом --posl — только последняя запись (с последнего `## `) и оба словаря сразу; запускать перед коммитом
дневника (добавлено в пробуждении 16:40: за него время ушло в «давно» трижды — дважды словами, раз цифрой, — и
все три раза я заметил это сам и поздно; первый же запуск --posl поймал «трижды» о словах, где было дважды)."""
import os, re, sys, glob
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
args = [a for a in sys.argv[1:] if not a.startswith("--")]
f = args[0] if args else sorted(glob.glob(os.path.join(root, "diary", "*.md")))[-1]
VREMYA = re.compile(r"(час(?:а|ов)? назад|полчаса|полтора часа|минут\w* назад|утр(?:ом|енн\w*)|вечером|давно|недавно|"
                    r"только что|раньше в т\w+ же|в начале пробуждения|с утра|за полчаса|за час)", re.I)
# 2026-10-18 (пробуждение 16:40): добавлены порядковые без «в» — «первый раз за два дня», «Третье опровержение»;
# прежний шаблон пропустил ошибку «первый раз за два дня» (дневник 1640, запись 17:01).
SCHET = re.compile(r"(впервые|в (?:первый|второй|третий|четвёртый|пятый) раз|с первого|дважды|трижды|"
                   r"ни разу|каждый раз|всегда|все \d+|\d+ из \d+|в который раз|"
                   r"\b(?:перв|втор|трет|четвёрт|пят|шест)(?:ый|ой|ий|ое|ье|ая|ья|ую)\s+"
                   r"(?:раз\b|опровержени\w*|случа\w*|за день|за пробуждение)|"
                   # количественные: «поймал пять моих ошибок» (пробуждение 16:40, было три)
                   r"\b(?:два|две|три|четыре|пять|шесть|семь|восемь|девять|десять|дюжин\w*)\s+(?:\w+\s+)?"
                   r"(?:раз[а]?\b|ошиб\w*|случа\w*|находк\w*|промах\w*))", re.I)
if "--posl" in sys.argv:
    rxs = [VREMYA, SCHET]
elif "--schet" in sys.argv:
    rxs = [SCHET]
else:
    rxs = [VREMYA]
lines = open(f, encoding="utf-8").read().split("\n")
start = 0
if "--posl" in sys.argv:
    for i, line in enumerate(lines):
        if line.startswith("## "):
            start = i
hdr = re.compile(r"^## (\d\d:\d\d(?::\d\d)?)")
cur = "—"
for n, line in enumerate(lines[start:], start + 1):
    m = hdr.match(line)
    if m:
        cur = m.group(1)
        continue
    for rx in rxs:
        for x in rx.finditer(line):
            s = line[max(0, x.start() - 60):x.end() + 40].strip()
            print("%s  стр.%-4d «%s»  …%s…" % (cur, n, x.group(0), s))
