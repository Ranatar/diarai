# Проверка чисел страницы geolympiad.html. Внешние константы помечены «по памяти».
yr = 3.156e7  # секунд в году

# 1. Занклийский потоп: 1000 м3/с, «за ~1000–10000 лет заполнив бассейн»
V_med = 3.75e15  # м3, объём Средиземного моря, по памяти (~3,75 млн км3)
t = V_med / 1000 / yr
print("потоп: при 1000 м3/с заполнение займёт %.0f лет" % t)
print("  нужный расход для 1000 лет: %.1e м3/с, для 10000 лет: %.1e м3/с" % (V_med / (1000 * yr), V_med / (10000 * yr)))

# 2. Тея: «размером с Марс», «~10 км/с», «эквивалент 10^29 Дж»
m_mars = 6.42e23  # кг, по памяти
E = 0.5 * m_mars * (1e4) ** 2
print("Тея: E = %.1e Дж; заявлено 1e29, расхождение в %.0f раз" % (E, E / 1e29))

# 3. Тихоокеанская: 103.3 млн км2, «сокращается ~3 км2/год», «конец через ~300–400 млн лет»
print("Тихоокеанская: 103.3e6 / 3 = %.1f млн лет" % (103.3e6 / 3 / 1e6))
print("  нужная скорость для 350 млн лет: %.2f км2/год" % (103.3e6 / 350e6))

# 4. Индия: 9000 км за 55 млн лет, «средняя 15–20 см/год»
print("Индия: 9000 км / 55 млн лет = %.1f см/год" % (9000e5 / 55e6))
print("  рекорд лиги по скорости — Фараллонская, ~18 см/год")

# 5. Эверест: 9000 − 8848.86 м при ~5 мм/год
print("Эверест до 9000 м: %.0f лет (заявлено ~30000)" % ((9000 - 8848.86) / 0.005))

# 6. Австралия: 2000–3000 км при 6–7 см/год
print("Австралия: %.0f–%.0f млн лет (заявлено 40–50)" % (2000e5 / 7 / 1e6, 3000e5 / 6 / 1e6))

# 7. Бюджет: «доступно 340», «потрачено 680 из 1000»
print("бюджет: 1000 − 680 = %d (заявлено доступно 340)" % (1000 - 680))

# 8. Фэнтези: 1247 + 988 − 44 + 312 + 0
print("фэнтези: %d (заявлено 2503)" % (1247 + 988 - 44 + 312 + 0))

# 9. Массы плит: площадь × 100 км × 3300 кг/м3 (литосфера, по памяти — грубо)
for name, area, mass in (("Индийская", 11.9e12, 1.54e23), ("Евразийская", 67.8e12, 5.51e23)):
    est = area * 1e5 * 3300
    print("%s: оценка %.1e кг, заявлено %.2e, в %.0f раз больше" % (name, est, mass, mass / est))
print("  (5.51 — это средняя плотность Земли в г/см3, по памяти; одно совпадение, не вывод)")

# 10. Пангея ~510 млн км2 против площади поверхности Земли
R = 6.371e6
print("поверхность Земли: %.0f млн км2; суша сейчас ~149 млн км2 (по памяти)" % (4 * 3.14159 * R ** 2 / 1e12))
