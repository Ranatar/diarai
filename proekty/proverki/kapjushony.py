from math import pi, log2, radians, degrees
print("каналы: 10×3 =", 10 * 3, "; 7×3 =", 7 * 3, "; 30×21 =", 30 * 21)
print("бит на кинему log2(400) = %.2f (страница: ≈ 9)" % log2(400))
rate = 1 / (0.8 + 0.3)
print("кинем в секунду 1/(0.8+0.3) = %.3f (страница: ~0.9); бит/с = %.1f (страница: ~8)" % (rate, rate * log2(400)))
vmax = pi / 2           # «θ̇_max ≈ π/2 рад/с»
dmin = radians(5)       # «Δθ_min ≈ 5°»
# синусоида θ = A sin(2πft): пиковая скорость 2πfA
for name, A_deg, f in (("трепет ≈ 5 Гц, A = Δθmin", 5, 5), ("трепет ≈ 10 Гц, A = Δθmin", 5, 10),
                       ("покачивание ±15° при 0.5 Гц", 15, 0.5), ("покачивание ±15° при 2 Гц", 15, 2)):
    v = 2 * pi * f * radians(A_deg)
    print("%-32s пиковая скорость %.2f рад/с — %s" % (name, v, "в пределе" if v <= vmax else "ВЫШЕ предела π/2 = 1.57"))
for f in (5, 10):
    A = vmax / (2 * pi * f)
    print("наибольшая амплитуда трепета при %d Гц: %.2f° (порог различимости 5°)" % (f, degrees(A)))
print("удар 0 → 45° → 0 при π/2 рад/с займёт не меньше %.2f с («резко»)" % (2 * radians(45) / vmax))
