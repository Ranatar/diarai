# Восьмиугольники в (2i,2j), квадраты в (2i+1,2j+1) (удвоенные координаты); 8 направлений по 45° (0 — восток, против часовой).
import sys
D=[(2,0),(1,1),(0,2),(-1,1),(-2,0),(-1,-1),(0,-2),(1,-1)]
def run(n, d0=0, right=-1):
    black=set(); x=y=0; d=d0; out=[0]
    for t in range(n):
        sq=(x%2==1)
        c=(x,y) in black
        turn=(2 if sq else 1)*(right if not c else -right)
        d=(d+turn)%8
        black^={(x,y)}
        dx,dy=D[d]; x+=dx; y+=dy
        out.append(len(black))
    return out
