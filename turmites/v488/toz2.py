# вант 4.8.8 с чётными To при старте к квадрату -> турмит 2×2 (мой код): состояние 0 = восьмиугольник, 1 = квадрат,
# запись ¬c, следующее состояние ¬s, поворот t (×45°, чётный) -> k=t/2 (×90° против часовой) -> tn=(-k)&3 (по часовой: 1=R)
import sys
def toz2(code):
    To=[code&7,(code>>3)&7]; Ts=[2*((code>>6)&3),2*((code>>8)&3)]
    assert To[0]%2==0 and To[1]%2==0
    r=0
    for s,T in ((0,To),(1,Ts)):
        for c in (0,1):
            e=2*s+c; tn=(-(T[c]//2))&3
            r|=((1-c)|(tn<<1)|((1-s)<<3))<<(4*e)
    return r
for a in sys.argv[1:]:
    r=toz2(int(a)); print(a,r)
