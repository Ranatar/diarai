here = os.path.dirname(os.path.abspath(__file__))
os.makedirs(os.path.join(here, 'img/zoo'), exist_ok=True)
md = ['# Зоопарк турмитов 2×2', '',
      'По одному представителю на тип. Номер — мой 16-битный код (см. NOTES.md), в скобках — нотация Пегга/Golly. '
      'Чёрное — клетки цвета 1, серое — где муравей побывал, белое — нетронутое поле.', '']
with tempfile.TemporaryDirectory() as tmp:
    for rule, steps, name, desc in ZOO:
        p = os.path.join(tmp, 'a.pgm')
        subprocess.run([os.path.join(here, 'render'), str(rule), str(steps), p], check=True, capture_output=True)
        im = Image.open(p); w, h = im.size
        k = 400 / max(w, h)
        im = im.resize((max(1, round(w * k)), max(1, round(h * k))), Image.NEAREST if k >= 1 else Image.LANCZOS)
        fn = f'img/zoo/{rule}.png'; im.save(os.path.join(here, fn))
        md += [f'## {name} — {rule} ({to_pegg(rule)})', '', desc, f'Шагов: {steps:,}'.replace(',', ' ') + f', размер {w}×{h}.', '', f'![{name}]({fn})', '']
open(os.path.join(here, 'ZOO.md'), 'w').write('\n'.join(md))
